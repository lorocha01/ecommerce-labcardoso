const BASE_DATE = '2026-01-10T12:00:00.000Z'

type Seed = Omit<Product, 'id' | 'slug' | 'active' | 'dataStatus' | 'createdAt' | 'updatedAt' | 'tone' | 'icon' | 'featured' | 'requiresPreparation' | 'importantInfo'> & {
  slug: string
  icon?: string
  tone?: ArtTone
  featured?: boolean
  requiresPreparation?: boolean
  importantInfo?: string
}

const DEFAULT_INFO =
  'Informação demonstrativa. As orientações de preparo podem variar conforme o pedido médico, uso de medicamentos e condições individuais. Confirme sempre com a equipe do laboratório antes da coleta.'

const catIcon: Record<string, { icon: string; tone: ArtTone }> = {
  'cat-sangue': { icon: 'droplet', tone: 'red' },
  'cat-hormonais': { icon: 'activity', tone: 'rose' },
  'cat-urina': { icon: 'flask', tone: 'sand' },
  'cat-fezes': { icon: 'beaker', tone: 'peach' },
  'cat-vitaminas': { icon: 'sun', tone: 'peach' },
  'cat-colesterol': { icon: 'heart', tone: 'wine' },
  'cat-glicose': { icon: 'gauge', tone: 'red' },
  'cat-checkups': { icon: 'clipboard', tone: 'wine' },
  'cat-especiais': { icon: 'microscope', tone: 'ink' },
}

function make(seed: Seed): Product {
  const visual = catIcon[seed.categoryId] ?? { icon: 'testtube', tone: 'red' as ArtTone }
  return {
    ...seed,
    id: seed.slug,
    slug: seed.slug,
    icon: seed.icon ?? visual.icon,
    tone: seed.tone ?? visual.tone,
    featured: seed.featured ?? false,
    requiresPreparation: seed.requiresPreparation ?? !/sem preparo/i.test(seed.preparationSummary),
    importantInfo: seed.importantInfo ?? DEFAULT_INFO,
    active: true,
    dataStatus: 'demonstrativo',
    createdAt: BASE_DATE,
    updatedAt: BASE_DATE,
  }
}

